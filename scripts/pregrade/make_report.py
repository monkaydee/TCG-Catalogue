"""Writes docs/PREGRADING-RESULTS.md from a run of train_grade_v2.py (and export_onnx.py, stress_test.py),
so the published numbers are the measured ones and nothing is copied by hand.

    python3 make_report.py RUN_DIR "which shards / how much data, in words"
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "../../docs/PREGRADING-RESULTS.md"))
NAMES = [
    ("no_information_training_grade_mix", "No information (always the commonest grade)"),
    ("catalogue_only_language_and_year", "Catalogue only: language and print year, **no picture**"),
    ("shipped_design_measured_monotone", "Measured, first model's design (50 measurements, monotone weights)"),
    ("measured", "Measured (50 measurements, free weights)"),
    ("learned", "Learned close-up features"),
    ("combined", "Measured + learned"),
    ("catalogue_plus_measured", "Catalogue + measured"),
    ("catalogue_plus_learned", "Catalogue + learned"),
]


def pct(v):
    return "–" if v is None else f"{100 * v:.1f} %"


def main(run, data_words):
    ev = json.load(open(os.path.join(run, "evaluation.json")))
    load = lambda n: json.load(open(os.path.join(run, n))) if os.path.isfile(os.path.join(run, n)) else None
    st, ex = load("stress_test.json"), load("export_check.json")
    d, m = ev["data"], ev["models"]
    L = []
    w = L.append
    w("# Pre-grader: measured results\n")
    w("Generated by `scripts/pregrade/make_report.py` from the run's `evaluation.json`. Do not edit by hand.")
    w("What these numbers mean for the app is in [PREGRADING-SYSTEM.md](PREGRADING-SYSTEM.md).\n")
    w("## Data\n")
    w(f"- Source: jyesr/pokemon-tcg-grading, {data_words}. PSA scans of slabbed Pokémon cards, front and back, about 18 px/mm.")
    w(f"- Cards read: {d['cards_read']}. Left out: {d['no_numeric_grade']} without a numeric grade (\"Authentic\" or empty), {d['qualified_grade']} with a qualified grade (OC, MC, …).")
    w(f"- Cards used: **{d['cards_used']}** physical cards ({2 * d['cards_used']} pictures at most), {d['printed_cards']} different printed cards.")
    w(f"- Split by printed card: train {d['train']}, validation {d['val']}, test {d['test']} ({d['split_groups']} groups; no group in two parts).")
    w("- Grades: " + ", ".join(f"PSA {g}: {n}" for g, n in d["grade_counts"].items()) + ".")
    w("- Languages: " + ", ".join(f"{k} {v}" for k, v in sorted(d["languages"].items(), key=lambda t: -t[1])) + ".")
    w("- One Piece cards: **0**. No graded One Piece data was available (sources.json).")
    w("- Defect annotations: **0**. The annotated datasets need an API key that was not available (sources.json).\n")
    w("## Grade models on the held-out test cards\n")
    w("Grades below 5 share one bucket (\"4 or lower\"), as in the first model. MAE = mean absolute error in grades. "
      "Brackets: 95 % bootstrap interval. \"75 % range\" is the app's rule: the smallest run of neighbouring grades that the model gives 75 % to.\n")
    w("| Model | MAE | Exact grade | Within one grade | AUC \"is it a 10?\" | 75 % range holds the true grade | Mean range width |")
    w("| --- | --- | --- | --- | --- | --- | --- |")
    for key, label in NAMES:
        s = m.get(key)
        if not s:
            continue
        ci = f" [{s['mae_ci95'][0]:.2f}–{s['mae_ci95'][1]:.2f}]" if "mae_ci95" in s else ""
        auc = f"{s['auc_ge_10']:.3f}" if "auc_ge_10" in s else "–"
        w(f"| {label} | {s['mae']:.3f}{ci} | {pct(s['exact'])} | {pct(s['within_1'])} | {auc} | {pct(s['range_75_coverage'])} | {s['range_75_mean_width']:.2f} grades |")
    w(f"\nTest cards: {m['learned']['n']}. Chosen on validation: **{ev['selection']['winner_by_validation']}**.\n")
    cat, lrn, cl = m["catalogue_only_language_and_year"], m["learned"], m.get("catalogue_plus_learned")
    w("### Reading the table\n")
    pg = ev["picture_gain_in_mae"]["catalogue_plus_learned_vs_catalogue_only"]
    w(f"- Knowing only the card's language and print year gives MAE {cat['mae']:.3f}. The learned picture features alone give {lrn['mae']:.3f}; "
      f"catalogue and pictures together {cl['mae']:.3f}.")
    real = pg["ci95"][0] > 0
    w(f"- Compared card by card on the same test cards, adding the pictures to the catalogue facts lowers the error by "
      f"**{pg['mean']:.3f} grades** (95 % interval {pg['ci95'][0]:+.3f} to {pg['ci95'][1]:+.3f}). "
      + ("That is a real but small gain. " if real else "The interval includes zero: no gain can be shown. ")
      + f"Going from no information to the catalogue alone lowers it by {m['no_information_training_grade_mix']['mae'] - cat['mae']:.3f}. "
      "So most of what a picture model appears to know is which kinds of cards usually get which grade, not the condition of this copy.")
    w(f"- The app's own 50 measurements (centering and rim wear), fitted on these scans, score {m['measured']['mae']:.3f}: "
      + ("worse than" if m["measured"]["mae"] > cat["mae"] else "no better than") + " the catalogue alone.")
    w("- A model is only useful for pre-grading to the extent that it beats the catalogue-only row.\n")
    g = ev.get("auc_grade_10_within_groups", {})
    if g:
        w("### Can the picture tell a 10 from the rest inside one kind of card?\n")
        w("AUC 0.5 = chance, 1.0 = perfect.\n")
        w("| Cards | Test cards | Share of 10s | Learned features | Catalogue only |")
        w("| --- | --- | --- | --- | --- |")
        for k, v in g.items():
            w(f"| {k} | {v['n']} | {pct(v['share_10'])} | {v['learned']:.3f} | {v['catalogue_only']:.3f} |")
        w("")
    win = ev["selection"]["winner_by_validation"]
    s = m[win]
    w(f"### Confusion matrix of the chosen model ({win})\n")
    gr = s["confusion_rows_true_cols_pred"]["grades"]
    w("Rows: true grade. Columns: predicted grade.\n")
    w("| true \\ predicted | " + " | ".join(("≤4" if x == 4 else str(x)) for x in gr) + " | recall | within one |")
    w("| --- |" + " --- |" * (len(gr) + 2))
    for t, row in zip(gr, s["confusion_rows_true_cols_pred"]["counts"]):
        w(f"| {'≤4' if t == 4 else t} | " + " | ".join(map(str, row)) + f" | {pct(s['per_grade_recall'][str(t)])} | {pct(s['per_grade_within_1'][str(t)])} |")
    w("")
    w(f"Calibration of \"10 or not\": expected calibration error {s['ece_ge_10']:.3f}. Bins (predicted chance from, cards, mean predicted, share that were 10):\n")
    w("| from | cards | predicted | actual |\n| --- | --- | --- | --- |")
    for a, n, p, t in s["reliability_ge_10"]:
        w(f"| {a:.1f} | {n} | {p:.3f} | {t:.3f} |")
    w("")
    sg = ev.get("subgroups_" + win, {})
    if sg:
        w(f"### Subgroups of the chosen model\n")
        w("| Cards | Test cards | MAE | Exact | Within one | 75 % range holds |\n| --- | --- | --- | --- | --- | --- |")
        for k, v in sg.items():
            w(f"| {k.replace('_', ' ')} | {v['n']} | {v['mae']:.3f} | {pct(v['exact'])} | {pct(v['within_1'])} | {pct(v['range_75_coverage'])} |")
        w("")
    hb = ev.get("held_out_submission_blocks_" + win)
    if hb:
        w("### Second test: whole submissions held out\n")
        w(f"A fifth of the runs of 50 consecutive certificates (usually one submission, one scanner batch) and all their artwork were held out: "
          f"{hb['n']} cards, trained on {hb['train']}. MAE {hb['mae']:.3f}, exact {pct(hb['exact'])}, within one {pct(hb['within_1'])}, "
          f"AUC for 10 {hb['auc_ge_10']:.3f}, 75 % range holds {pct(hb['range_75_coverage'])}.\n")
    if st:
        w("## Robustness: the same unseen cards, pictured worse\n")
        w(f"{st['cards']} cards from a shard not used for fitting, scored with the learned-features model. Each was scored from the scan and from a degraded copy ({st['degradation']}).\n")
        w("| | Scan | Degraded copy |\n| --- | --- | --- |")
        w(f"| MAE | {st['mae_scan']:.3f} | {st['mae_degraded']:.3f} |")
        w(f"| Within one grade | {pct(st['within_1_scan'])} | {pct(st['within_1_degraded'])} |")
        w(f"| Called a 10 | {pct(st['share_called_10_scan'])} | {pct(st['share_called_10_degraded'])} |")
        w(f"\nSame most likely grade for both versions: {pct(st['same_most_likely_grade'])}. Mean shift of the expected grade: "
          f"{st['mean_shift_in_expected_grade']:+.2f} (mean absolute shift {st['mean_absolute_shift_in_expected_grade']:.2f}).")
        w("This simulates only resolution, blur, compression and colour. Real phone photos add glare, perspective, sleeves and shadows.\n")
    if ex:
        w("## Export\n")
        w(f"- `closeup_features.onnx`: {ex['onnx_bytes'] / 1e6:.1f} MB, largest difference to PyTorch {ex['max_abs_difference_features_onnx_vs_torch']:.1e}.")
        w(f"- `grade_head.json`: {ex['head_bytes'] / 1e3:.0f} kB, largest difference in probabilities to scikit-learn {ex['max_abs_difference_probabilities_head_vs_sklearn']:.1e}.\n")
    w("## Training configuration\n")
    sel = ev["selection"]
    w("- Feature network: MobileNetV3-small, ImageNet weights (torchvision, BSD), frozen. 28 close-ups of 256×256 scan pixels per card "
      "(4 corners and 10 edge windows per side) plus the whole card per side, each resized to 224×224; 720 numbers per view.")
    w("- Head: one logistic model per threshold (\"grade k or better\", k = 10 … 5) on standardised features; the chance of a lower bar is never below that of a higher one.")
    w(f"- Chosen on validation: learned C={sel['learned']['C']}, PCA {sel['learned']['pca']} components; measured C={sel['measured']['C']}; combined C={sel['combined']['C']}.")
    w("- Augmentation: none. Seed 7. Hardware: 2 CPU cores, no GPU.")
    w(f"- Fitting and scoring time: {ev['seconds']:.0f} s (after feature extraction, about 0.8 s per card).\n")
    open(OUT, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
